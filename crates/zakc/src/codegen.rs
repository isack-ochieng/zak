use std::collections::HashMap;

use crate::ast::{BinaryOperator, Expression, Function, Program, Statement, UnaryOperator};
use crate::checker::Type;
use crate::diagnostic::{Diagnostic, Span};

struct Value { operand: String, ty: Type }
struct VariableSlot { pointer: String, ty: Type }

struct FunctionGenerator {
    body: String,
    globals: Vec<String>,
    variables: HashMap<String, VariableSlot>,
    next_temp: usize,
    next_slot: usize,
    next_string: usize,
    used_puts: bool,
    used_printf: bool,
}

pub fn generate(program: &Program) -> Result<String, Diagnostic> {
    let function = program.functions.iter().find(|function| function.name == "main")
        .ok_or_else(|| Diagnostic::new("codegen", "missing main function", Span::new(1, 1)))?;

    let mut generator = FunctionGenerator {
        body: String::new(), globals: Vec::new(), variables: HashMap::new(),
        next_temp: 0, next_slot: 0, next_string: 0, used_puts: false, used_printf: false,
    };
    generator.generate_function(function)?;

    let mut module = String::from("; Generated by the ZAK compiler. Do not edit.\nsource_filename = \"zak-module\"\n\n");
    module.push_str("@.zak.fmt.int = private unnamed_addr constant [5 x i8] c\"%ld\\0A\\00\", align 1\n");
    module.push_str("@.zak.true = private unnamed_addr constant [5 x i8] c\"true\\00\", align 1\n");
    module.push_str("@.zak.false = private unnamed_addr constant [6 x i8] c\"false\\00\", align 1\n");
    for global in &generator.globals { module.push_str(global); module.push('\n'); }
    module.push('\n');

    if generator.used_puts { module.push_str("declare i32 @puts(ptr)\n"); }
    if generator.used_printf { module.push_str("declare i32 @printf(ptr, ...)\n"); }
    if generator.used_puts || generator.used_printf { module.push('\n'); }

    module.push_str("define i32 @main() {\nentry:\n");
    module.push_str(&generator.body);
    module.push_str("}\n");
    Ok(module)
}

impl FunctionGenerator {
    fn generate_function(&mut self, function: &Function) -> Result<(), Diagnostic> {
        let mut terminated = false;
        for statement in &function.body {
            if terminated { break; }
            terminated = self.generate_statement(statement)?;
        }
        if !terminated { self.body.push_str("  ret i32 0\n"); }
        Ok(())
    }

    fn generate_statement(&mut self, statement: &Statement) -> Result<bool, Diagnostic> {
        match statement {
            Statement::Variable { name, initializer, .. } => {
                let slot = format!("%slot{}", self.next_slot);
                self.next_slot += 1;
                let value = self.generate_expression(initializer)?;
                self.body.push_str(&format!("  {} = alloca {}\n", slot, value.ty.llvm_type()));
                self.body.push_str(&format!("  store {} {}, ptr {}\n", value.ty.llvm_type(), value.operand, slot));
                self.variables.insert(name.clone(), VariableSlot { pointer: slot, ty: value.ty });
                Ok(false)
            }
            Statement::Assignment { name, value, .. } => {
                let (pointer, ty) = self.variables.get(name)
                    .map(|slot| (slot.pointer.clone(), slot.ty))
                    .ok_or_else(|| Diagnostic::new("codegen", format!("unknown variable '{}'", name), value.span()))?;
                let value = self.generate_expression(value)?;
                self.body.push_str(&format!("  store {} {}, ptr {}\n", ty.llvm_type(), value.operand, pointer));
                Ok(false)
            }
            Statement::Return { value, .. } => {
                if let Some(expression) = value {
                    let value = self.generate_expression(expression)?;
                    let result = self.temp();
                    self.body.push_str(&format!("  {} = trunc i64 {} to i32\n", result, value.operand));
                    self.body.push_str(&format!("  ret i32 {}\n", result));
                } else {
                    self.body.push_str("  ret i32 0\n");
                }
                Ok(true)
            }
            Statement::Expression { expression, .. } => {
                self.generate_expression(expression)?;
                Ok(false)
            }
        }
    }

    fn generate_expression(&mut self, expression: &Expression) -> Result<Value, Diagnostic> {
        match expression {
            Expression::Integer(value, _) => Ok(Value { operand: value.to_string(), ty: Type::Int }),
            Expression::Boolean(value, _) => Ok(Value {
                operand: if *value { "true" } else { "false" }.to_string(), ty: Type::Bool,
            }),
            Expression::String(value, _) => {
                let (name, length) = self.add_string(value);
                Ok(Value { operand: Self::global_pointer(&name, length), ty: Type::String })
            }
            Expression::Variable(name, span) => {
                let (pointer, ty) = self.variables.get(name)
                    .map(|slot| (slot.pointer.clone(), slot.ty))
                    .ok_or_else(|| Diagnostic::new("codegen", format!("unknown variable '{}'", name), *span))?;
                let result = self.temp();
                self.body.push_str(&format!("  {} = load {}, ptr {}\n", result, ty.llvm_type(), pointer));
                Ok(Value { operand: result, ty })
            }
            Expression::Unary { operator, operand, .. } => {
                let operand = self.generate_expression(operand)?;
                let result = self.temp();
                let ty = match operator {
                    UnaryOperator::Negate => {
                        self.body.push_str(&format!("  {} = sub i64 0, {}\n", result, operand.operand));
                        Type::Int
                    }
                    UnaryOperator::Not => {
                        self.body.push_str(&format!("  {} = xor i1 {}, true\n", result, operand.operand));
                        Type::Bool
                    }
                };
                Ok(Value { operand: result, ty })
            }
            Expression::Binary { left, operator, right, .. } => {
                let left_value = self.generate_expression(left)?;
                let right_value = self.generate_expression(right)?;
                let result = self.temp();
                use BinaryOperator::*;
                let instruction = match operator {
                    Add => format!("add i64 {}, {}", left_value.operand, right_value.operand),
                    Subtract => format!("sub i64 {}, {}", left_value.operand, right_value.operand),
                    Multiply => format!("mul i64 {}, {}", left_value.operand, right_value.operand),
                    Divide => format!("sdiv i64 {}, {}", left_value.operand, right_value.operand),
                    Remainder => format!("srem i64 {}, {}", left_value.operand, right_value.operand),
                    Equal => format!("icmp eq {} {}, {}", left_value.ty.llvm_type(), left_value.operand, right_value.operand),
                    NotEqual => format!("icmp ne {} {}, {}", left_value.ty.llvm_type(), left_value.operand, right_value.operand),
                    Less => format!("icmp slt i64 {}, {}", left_value.operand, right_value.operand),
                    LessEqual => format!("icmp sle i64 {}, {}", left_value.operand, right_value.operand),
                    Greater => format!("icmp sgt i64 {}, {}", left_value.operand, right_value.operand),
                    GreaterEqual => format!("icmp sge i64 {}, {}", left_value.operand, right_value.operand),
                    And => format!("and i1 {}, {}", left_value.operand, right_value.operand),
                    Or => format!("or i1 {}, {}", left_value.operand, right_value.operand),
                };
                self.body.push_str(&format!("  {} = {}\n", result, instruction));
                let ty = match operator {
                    Equal | NotEqual | Less | LessEqual | Greater | GreaterEqual | And | Or => Type::Bool,
                    _ => Type::Int,
                };
                Ok(Value { operand: result, ty })
            }
            Expression::Call { callee, arguments, span } => {
                if callee != "print" || arguments.len() != 1 {
                    return Err(Diagnostic::new("codegen", "unsupported function call", *span));
                }
                let value = self.generate_expression(&arguments[0])?;
                match value.ty {
                    Type::String => {
                        self.used_puts = true;
                        self.body.push_str(&format!("  call i32 @puts(ptr {})\n", value.operand));
                    }
                    Type::Int => {
                        self.used_printf = true;
                        self.body.push_str(&format!("  call i32 (ptr, ...) @printf(ptr {}, i64 {})\n",
                            Self::global_pointer(".zak.fmt.int", 5), value.operand));
                    }
                    Type::Bool => {
                        self.used_puts = true;
                        let selected = self.temp();
                        self.body.push_str(&format!("  {} = select i1 {}, ptr {}, ptr {}\n", selected, value.operand,
                            Self::global_pointer(".zak.true", 5), Self::global_pointer(".zak.false", 6)));
                        self.body.push_str(&format!("  call i32 @puts(ptr {})\n", selected));
                    }
                    Type::Unit => return Err(Diagnostic::new("codegen", "cannot print a Unit value", *span)),
                }
                Ok(Value { operand: String::new(), ty: Type::Unit })
            }
        }
    }

    fn temp(&mut self) -> String {
        let name = format!("%t{}", self.next_temp);
        self.next_temp += 1;
        name
    }

    fn add_string(&mut self, value: &str) -> (String, usize) {
        let name = format!(".zak.str.{}", self.next_string);
        self.next_string += 1;
        let length = value.as_bytes().len() + 1;
        let escaped = llvm_escape(value.as_bytes());
        self.globals.push(format!("@{} = private unnamed_addr constant [{} x i8] c\"{}\", align 1", name, length, escaped));
        (name, length)
    }

    fn global_pointer(name: &str, length: usize) -> String {
        format!("getelementptr inbounds ([{} x i8], ptr @{}, i64 0, i64 0)", length, name)
    }
}

fn llvm_escape(bytes: &[u8]) -> String {
    let mut escaped = String::new();
    for byte in bytes {
        match *byte {
            b' '..=b'~' if *byte != b'"' && *byte != b'\\' => escaped.push(*byte as char),
            _ => escaped.push_str(&format!("\\{:02X}", byte)),
        }
    }
    escaped.push_str("\\00");
    escaped
}
